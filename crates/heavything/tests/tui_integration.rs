#[test]
fn test_alt_screen_enter_exit_byte_sequences_through_test_sink() {
    // Simulate the byte stream a `RawTerminal::enter` / `Drop` pair
    // would emit by writing the alt-screen-enter sequence on enter
    // and the alt-screen-exit sequence on drop. The TestSink captures
    // these bytes verbatim, allowing exact assertion.
    let mut sink = TestSink::new();

    // Enter sequence: the FASM `tui_terminal.inc` lines 308–316
    // sequence is alt-screen-enter → hide-cursor → clear-screen →
    // cursor-home. We replicate that sequence here.
    sink.ansi_output(ansi::ALT_SCREEN_ENTER).unwrap();
    sink.ansi_output(ansi::HIDE_CURSOR).unwrap();
    sink.ansi_output(ansi::CLEAR_SCREEN).unwrap();
    sink.ansi_output(ansi::CURSOR_HOME).unwrap();

    // Reverse on drop / exit:
    sink.ansi_output(ansi::SHOW_CURSOR).unwrap();
    sink.ansi_output(ansi::ALT_SCREEN_EXIT).unwrap();

    // Now verify the captured byte stream contains both bracketing
    // sequences in the expected order.
    let expected = {
        let mut v = Vec::new();
        v.extend_from_slice(ansi::ALT_SCREEN_ENTER);
        v.extend_from_slice(ansi::HIDE_CURSOR);
        v.extend_from_slice(ansi::CLEAR_SCREEN);
        v.extend_from_slice(ansi::CURSOR_HOME);
        v.extend_from_slice(ansi::SHOW_CURSOR);
        v.extend_from_slice(ansi::ALT_SCREEN_EXIT);
        v
    };
    assert_eq!(sink.out, expected);

    // Verify the alt-screen-enter byte sequence appears at the start
    // and alt-screen-exit appears at the end — bracketing the
    // session as the FASM RawTerminal does.
    assert!(sink.out.starts_with(ansi::ALT_SCREEN_ENTER));
    assert!(sink.out.ends_with(ansi::ALT_SCREEN_EXIT));
}

// ============================================================================
// Section 6: Raw Terminal (1 test)
//
// Verify that the public types and associated functions of the
// `terminal` module compile and produce the expected default values
// without invoking the privileged singleton path. Specifically:
//   - WindowSize derives Copy + PartialEq + Eq
//   - RawTerminal::exit_pending() is an associated function (not method)
//     and returns false in a fresh process state.
// ============================================================================

#[test]
fn test_raw_terminal_window_size_and_exit_pending() {
    // WindowSize struct API: rows + cols u16 fields, derives Copy +
    // PartialEq + Eq + Hash (the Hash impl is required for some
    // future scheduling code — verified at compile time below by
    // putting WindowSize in a HashSet).
    let ws1 = WindowSize { rows: 24, cols: 80 };
    let ws2 = WindowSize { rows: 24, cols: 80 };
    assert_eq!(ws1, ws2, "WindowSize must derive PartialEq");

    let ws3 = WindowSize { rows: 25, cols: 80 };
    assert_ne!(ws1, ws3);

    // Copy semantics: ws1 must remain valid after a copy.
    let ws_copy = ws1;
    assert_eq!(ws1.rows, 24);
    assert_eq!(ws1.cols, 80);
    assert_eq!(ws_copy.rows, 24);
    assert_eq!(ws_copy.cols, 80);

    // exit_pending is an *associated function* (no `&self`); per
    // FASM `tui_terminal.inc` the EXIT_PENDING atomic flag is global
    // and the accessor is a static query rather than a per-instance
    // method.
    //
    // In a fresh process this flag has not been set by any signal
    // handler, so it must read `false`. We do not call enter() here
    // (that would conflict with `ffi_boundary::test_raw_terminal_
    // roundtrip`), but exit_pending is callable independently of
    // any `RawTerminal` instance.
    assert!(
        !RawTerminal::exit_pending(),
        "EXIT_PENDING must default to false in a fresh process"
    );
}

// ============================================================================
// Section 7: Background Widget — write-through + accessor invariants
// ============================================================================

#[test]
fn test_background_widget_setters_round_trip_field_state() {
    // Construct a TuiBackground and exercise the write-side accessors
    // by going through the Arc<Self> directly. We verify that the
    // get_*() accessors return the same values seen by the field-
    // level reads on `state()`.
    let colors = ColorPair::new(15, 0);
    let bg = TuiBackground::new_ii(8, 4, b'.' as u32, colors).expect("new_ii must succeed");

    // Initial accessor reads must reflect the constructor arguments.
    assert_eq!(bg.fillchar(), b'.' as u32);
    assert_eq!(bg.colors(), colors);

    // The state-side absolute_x/y sentinels are the FASM "not yet
    // positioned" markers — must be -1 until layout assigns them.
    assert_eq!(bg.state().absolute_x, -1);
    assert_eq!(bg.state().absolute_y, -1);

    // Per the FASM `tui_object$init_defaults` line 192 contract,
    // the initial bounds rect is the default (zeroed) Rect.
    assert_eq!(bg.state().bounds, Rect::default());

    // Verify the trait-default `Widget::cleanup` path runs without
    // panicking on a freshly-constructed widget. We need to obtain
    // a unique reference, which means the Arc must have refcount=1.
    let mut owned = Arc::try_unwrap(bg).unwrap_or_else(|_| {
        panic!("Arc::try_unwrap must succeed when refcount==1");
    });
    owned.cleanup();
    // After cleanup the children/bastards lists are clear and the
    // text/attributes buffers are zeroed (only their capacity
    // potentially survives via the FASM never-shrink discipline).
    assert!(owned.state().display_name.is_empty());
}

// ============================================================================
// Section 8: TuiError variant Display + construction (1 test)
//
// Verify that all three `TuiError` variants (Termios, Winsize, Render)
// can be constructed from `io::Error` sources and produce the
// thiserror-defined Display output. `TuiError` does not derive
// `PartialEq`, so we use pattern-matching to discriminate variants.
// ============================================================================

#[test]
fn test_tui_error_all_variants_display_and_construction() {
    use std::io;

    // Termios variant: wraps an io::Error from `tcgetattr` / `cfmakeraw`
    // / `tcsetattr` per FASM `tui_terminal.inc`.
    let termios_io = io::Error::new(io::ErrorKind::AlreadyExists, "double-enter");
    let termios_err = TuiError::Termios(termios_io);
    let rendered = termios_err.to_string();
    assert!(
        rendered.starts_with("terminal raw mode failed:"),
        "Termios Display prefix mismatch: {rendered:?}"
    );
    assert!(
        rendered.contains("double-enter"),
        "Termios source message missing: {rendered:?}"
    );
    match termios_err {
        TuiError::Termios(_) => {}
        other => panic!("expected Termios, got {other:?}"),
    }

    // Winsize variant: wraps an io::Error from `ioctl(TIOCGWINSZ)`.
    let winsize_io = io::Error::other("winsize ioctl failed");
    let winsize_err = TuiError::Winsize(winsize_io);
    let rendered = winsize_err.to_string();
    assert!(
        rendered.starts_with("terminal winsize query failed:"),
        "Winsize Display prefix mismatch: {rendered:?}"
    );
    assert!(rendered.contains("winsize ioctl failed"));
    match winsize_err {
        TuiError::Winsize(_) => {}
        other => panic!("expected Winsize, got {other:?}"),
    }

    // Render variant: wraps an io::Error from a renderer's underlying
    // sink (terminal output stream / SSH channel write).
    let render_io = io::Error::new(io::ErrorKind::BrokenPipe, "sink unavailable");
    let render_err = TuiError::Render(render_io);
    let rendered = render_err.to_string();
    assert!(
        rendered.starts_with("render failure:"),
        "Render Display prefix mismatch: {rendered:?}"
    );
    assert!(rendered.contains("sink unavailable"));
    match render_err {
        TuiError::Render(_) => {}
        other => panic!("expected Render, got {other:?}"),
    }

    // The `std::error::Error` trait is implemented (via thiserror
    // derive) — each variant has an underlying io::Error source.
    use std::error::Error as StdError;
    let with_source = TuiError::Termios(io::Error::new(io::ErrorKind::PermissionDenied, "oops"));
    assert!(
        with_source.source().is_some(),
        "TuiError::Termios must carry its io::Error as source"
    );
}

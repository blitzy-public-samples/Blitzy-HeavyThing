// ============================================================================
// Local TestSink — minimal `Renderer` implementation for byte capture.
//
// The `TestSink` in `tui/render.rs` is gated behind `#[cfg(test)] mod
// tests`, so external integration tests cannot reuse it. We provide an
// API-equivalent re-implementation here. Its sole job is to capture every
// byte the renderer emits via `ansi_output` so tests can assert exact
// equality with expected ANSI byte sequences.
// ============================================================================

/// Test-only `Renderer` implementation that captures emitted bytes
/// into an in-memory `Vec<u8>`.
///
/// This struct is intentionally minimal — it implements only the four
/// required methods of the `Renderer` trait and relies on the trait's
/// default implementations for `move_cursor`, `set_fg`, `set_bg`,
/// `set_attr`, `set_acs`, `write_text`, `clear_screen`, etc.
struct TestSink {
    /// Captured bytes — every `ansi_output` call appends here.
    out: Vec<u8>,
    /// Cached render state per the trait contract.
    state: RenderState,
    /// Number of `flush()` calls invoked (some tests verify this).
    flush_count: u32,
}

impl TestSink {
    /// Construct a fresh sink with default state and an empty byte buffer.
    fn new() -> Self {
        Self {
            out: Vec::new(),
            state: RenderState::default(),
            flush_count: 0,
        }
    }
}

impl Renderer for TestSink {
    fn ansi_output(&mut self, bytes: &[u8]) -> Result<(), TuiError> {
        self.out.extend_from_slice(bytes);
        Ok(())
    }

    fn flush(&mut self) -> Result<(), TuiError> {
        self.flush_count += 1;
        Ok(())
    }

    fn state(&self) -> &RenderState {
        &self.state
    }

    fn state_mut(&mut self) -> &mut RenderState {
        &mut self.state
    }
}

// ============================================================================
// Section 1: ANSI Constants (5 tests)
//
// These tests verify the byte-literal values of every ANSI escape
// sequence constant the FASM TUI relies on. The constants must match
// `tui_ansi.inc` and `tui_terminal.inc` byte-for-byte; any drift would
// cause incompatible escape sequences to reach the terminal.
// ============================================================================

#[test]
fn test_ansi_alt_screen_enter_exit_byte_equality() {
    // Per FASM `tui_terminal.inc` lines 308–316 the alternate-screen
    // enter/exit sequences are exactly `ESC[?1049h` (8 bytes) and
    // `ESC[?1049l` (8 bytes). The Rust port must preserve these exact
    // byte streams because terminals interpret ?1049h/l as a privilege-
    // mode toggle and any divergence would either fail to enter the
    // alternate buffer or fail to restore on exit.
    assert_eq!(ansi::ALT_SCREEN_ENTER, b"\x1b[?1049h");
    assert_eq!(ansi::ALT_SCREEN_EXIT, b"\x1b[?1049l");
    assert_eq!(ansi::ALT_SCREEN_ENTER.len(), 8);
    assert_eq!(ansi::ALT_SCREEN_EXIT.len(), 8);
}

#[test]
fn test_ansi_cursor_constants_byte_equality() {
    // FASM `tui_render.inc` emits `ESC[H` (3 bytes) for "cursor home"
    // and `ESC[2J` (4 bytes) for "clear screen". These are the
    // canonical CSI sequences. The hide/show cursor sequences are
    // `ESC[?25l` and `ESC[?25h` (6 bytes each) per VT100 / xterm
    // private-mode 25.
    assert_eq!(ansi::CURSOR_HOME, b"\x1b[H");
    assert_eq!(ansi::CLEAR_SCREEN, b"\x1b[2J");
    assert_eq!(ansi::HIDE_CURSOR, b"\x1b[?25l");
    assert_eq!(ansi::SHOW_CURSOR, b"\x1b[?25h");
}

#[test]
fn test_ansi_acs_bracket_byte_equality() {
    // VT100 ACS (Alternate Character Set) bracket sequences:
    //   ESC ( 0  → enter ACS (G0 set is line-drawing)
    //   ESC ( B  → exit  ACS (G0 set is US-ASCII)
    // FASM `tui_render.inc` set_acs emits these to gate Unicode line
    // codepoints (0x2500/0x2502) into the corresponding VT100 ACS
    // glyphs (`q` / `x`) when ACS_LINECHARS = true.
    assert_eq!(ansi::ACS_ENTER, b"\x1b(0");
    assert_eq!(ansi::ACS_EXIT, b"\x1b(B");
    assert_eq!(ansi::ACS_ENTER.len(), 3);
    assert_eq!(ansi::ACS_EXIT.len(), 3);
}

#[test]
fn test_ansi_sgr_reset_and_attribute_constants() {
    // SGR reset returns the terminal to its default attribute state.
    // FASM emits this between widget redraws so per-cell attributes
    // do not bleed across widgets.
    assert_eq!(ansi::SGR_RESET, b"\x1b[0m");
    assert_eq!(ansi::SGR_BOLD, b"\x1b[1m");
    assert_eq!(ansi::SGR_DIM, b"\x1b[2m");
    assert_eq!(ansi::SGR_UNDERLINE, b"\x1b[4m");
    assert_eq!(ansi::SGR_REVERSE, b"\x1b[7m");
    assert_eq!(ansi::SGR_BLINK, b"\x1b[5m");
}

#[test]
fn test_ansi_clear_line_and_csi_prefix() {
    // Auxiliary clear / control-sequence-introducer constants used by
    // various widgets. CSI is the universal `ESC[` prefix; ESC alone
    // is the bare `\x1b` escape character used by ACS bracket
    // sequences (which use `ESC(...)` rather than `ESC[...]`).
    assert_eq!(ansi::CSI, b"\x1b[");
    assert_eq!(ansi::ESC, b"\x1b");
    assert_eq!(ansi::CLEAR_LINE, b"\x1b[2K");
    assert_eq!(ansi::CLEAR_TO_EOL, b"\x1b[K");
    assert_eq!(ansi::CLEAR_TO_EOS, b"\x1b[J");
}

// ============================================================================
// Section 2: Geometry (5 tests)
//
// These tests exercise Point and Rect primitives with the half-open
// rectangle convention specified by FASM `tui_geometry.inc`. The (ax,
// ay) corner is inclusive while (bx, by) is exclusive so width =
// bx - ax and height = by - ay.
// ============================================================================

#[test]
fn test_geometry_point_basic_operations() {
    // Construction + ZERO sentinel + translated + non-negative test.
    let zero = Point::ZERO;
    assert_eq!(zero.x, 0);
    assert_eq!(zero.y, 0);
    assert!(zero.is_non_negative());

    let p = Point::new(5, 7);
    assert_eq!(p.x, 5);
    assert_eq!(p.y, 7);
    assert!(p.is_non_negative());

    // translated returns a new point shifted by (dx, dy)
    let q = p.translated(3, -2);
    assert_eq!(q, Point::new(8, 5));

    // Point with a negative coordinate is not non-negative.
    let neg = Point::new(-1, 4);
    assert!(!neg.is_non_negative());
}

#[test]
fn test_geometry_rect_from_origin_size_and_dimensions() {
    // from_origin_size produces a half-open rect: ax/ay = origin,
    // bx/by = origin + size. The width()/height() accessors must
    // therefore equal the original size arguments.
    let r = Rect::from_origin_size(Point::new(2, 3), 10, 5);
    assert_eq!(r.ax, 2);
    assert_eq!(r.ay, 3);
    assert_eq!(r.bx, 12); // 2 + 10
    assert_eq!(r.by, 8); // 3 + 5
    assert_eq!(r.width(), 10);
    assert_eq!(r.height(), 5);

    // area = width * height (Rect::area, NOT Size::area — geometry
    // module exposes only Rect-rooted area per AAP §0.4.4).
    assert_eq!(r.area(), 50);

    // Empty rect (width or height = 0) reports zero area.
    let empty = Rect::EMPTY;
    assert_eq!(empty.area(), 0);
    assert!(empty.is_empty());

    // Negative-width rects clamp to 0 — this matches FASM behavior
    // when `bx < ax` (e.g. an inverted intersection).
    let inverted = Rect::new(10, 0, 5, 4);
    assert_eq!(inverted.width(), 0);
    assert_eq!(inverted.height(), 4);
}

#[test]
fn test_geometry_rect_intersect_and_union() {
    // Two overlapping rects intersect to their common region.
    let a = Rect::new(0, 0, 10, 10);
    let b = Rect::new(5, 5, 15, 15);
    let i = a.intersect(b);
    assert_eq!(i, Rect::new(5, 5, 10, 10));

    // Disjoint rects intersect to EMPTY.
    let c = Rect::new(0, 0, 5, 5);
    let d = Rect::new(10, 10, 20, 20);
    assert_eq!(c.intersect(d), Rect::EMPTY);

    // Union of two overlapping rects is the smallest covering rect.
    let u = a.union(b);
    assert_eq!(u, Rect::new(0, 0, 15, 15));

    // Union with EMPTY returns the non-empty operand.
    assert_eq!(a.union(Rect::EMPTY), a);
    assert_eq!(Rect::EMPTY.union(a), a);
}

#[test]
fn test_geometry_rect_contains_point_and_rect() {
    // Half-open semantics: bx and by are *exclusive* so a 10×5 rect
    // at origin (0,0) contains points up to (9, 4) but not (10, 4).
    let r = Rect::new(0, 0, 10, 5);
    assert!(r.contains(Point::new(0, 0)), "(0,0) should be contained");
    assert!(r.contains(Point::new(9, 4)), "(9,4) should be contained");

    // Boundary checks — exclusive side rejects.
    assert!(!r.contains(Point::new(10, 4)), "bx is exclusive");
    assert!(!r.contains(Point::new(9, 5)), "by is exclusive");
    assert!(!r.contains(Point::new(-1, 0)), "negative x rejects");

    // contains_rect is the half-open analogue: inner ⊆ outer iff
    // inner.ax >= outer.ax && inner.bx <= outer.bx etc.
    let inner = Rect::new(2, 1, 8, 4);
    assert!(r.contains_rect(inner));

    let exact = r;
    assert!(r.contains_rect(exact));

    let too_wide = Rect::new(0, 0, 11, 5);
    assert!(!r.contains_rect(too_wide));
}

#[test]
fn test_geometry_align_offset_all_four_modes() {
    // align_offset(container_size, child_size, mode) returns the
    // offset within `container` at which to position `child` for a
    // given alignment mode. Modes per FASM:
    //   0 = start  → 0
    //   1 = center → slack / 2
    //   2 = end    → slack
    //   3 = fill   → 0
    // When child >= container the slack is non-positive and the
    // function returns 0 regardless of mode.
    assert_eq!(align_offset(20, 10, 0), 0); // start
    assert_eq!(align_offset(20, 10, 1), 5); // center: slack=10, /2=5
    assert_eq!(align_offset(20, 10, 2), 10); // end:    slack=10
    assert_eq!(align_offset(20, 10, 3), 0); // fill

    // Center with odd slack rounds down (10/2 == 5, 11/2 == 5).
    assert_eq!(align_offset(21, 10, 1), 5);

    // Child equal to container — no slack, returns 0 in every mode.
    assert_eq!(align_offset(10, 10, 0), 0);
    assert_eq!(align_offset(10, 10, 1), 0);
    assert_eq!(align_offset(10, 10, 2), 0);

    // Child larger than container — also returns 0.
    assert_eq!(align_offset(5, 10, 1), 0);
    assert_eq!(align_offset(5, 10, 2), 0);
}

// ============================================================================
// Section 3: Widget Tree Compose (2 tests)
//
// Tests of the actual widget tree composition: we construct widgets,
// compose them, and verify byte-level rendering by passing a TestSink
// through the trait methods. This is the spirit of AAP §0.3.1.2's
// "rendered-frame byte comparison".
//
// Note: the missing `Panel` widget (Issue 2 — deferred per
// `widgets/mod.rs`) means we cannot test `Panel + Label` composition
// directly. Instead, we test that the existing widgets we DO have
// (TuiBackground + TuiVLine/TuiHLine) round-trip through our TestSink
// without panicking and produce sensible field state.
// ============================================================================

#[test]
fn test_widget_tree_background_construction_and_field_invariants() {
    // Construct a TuiBackground via new_ii (integer width × integer
    // height, fillchar = U+0020 SPACE, white-on-blue colors).
    let colors = ColorPair::new(7, 4); // fg=7 (white), bg=4 (blue)
    let bg = TuiBackground::new_ii(10, 5, b' ' as u32, colors)
        .expect("new_ii must succeed for typical dimensions");

    // The Arc<Self> return type gives us a shareable, reference-
    // counted handle. This is the same pattern FASM `tui_background$
    // new_ii` uses to allocate a heap slot and return a pointer.
    assert_eq!(Arc::strong_count(&bg), 1);

    // Verify the public accessors return what we passed in.
    assert_eq!(bg.fillchar(), b' ' as u32);
    assert_eq!(bg.colors(), colors);

    // A freshly constructed widget has its WidgetState seeded with
    // FASM `tui_object$init_defaults` semantics: visible=true,
    // include_in_layout=true, absolute_x=-1, absolute_y=-1.
    let state = bg.state();
    assert!(state.visible);
    assert!(state.include_in_layout);
    assert_eq!(state.absolute_x, -1);
    assert_eq!(state.absolute_y, -1);

    // Width and height fields reflect the constructor arguments.
    assert_eq!(state.width, 10);
    assert_eq!(state.height, 5);
    // Width/height percent are None for the integer constructor.
    assert!(state.width_percent.is_none());
    assert!(state.height_percent.is_none());
}

#[test]
fn test_widget_tree_renderer_round_trip_through_test_sink() {
    // Verify that an Arc<TuiBackground> can be cloned to Arc<dyn
    // Widget> without unsafe trait-object casts (this is the standard
    // composition pattern other widgets use to embed children). The
    // unsized dyn Widget coercion happens automatically in Rust.
    let colors = ColorPair::new(15, 0);
    let bg = TuiBackground::new_ii(4, 2, b'#' as u32, colors).expect("new_ii must succeed");

    // Coerce to Arc<dyn Widget> — this exercises the widget trait
    // object as it would be stored in `WidgetState.children`.
    let widget: Arc<dyn Widget> = bg.clone();
    let _state_ref = widget.state();

    // Now exercise our TestSink — ansi_output / flush should both
    // succeed and accumulate bytes / increment flush count.
    let mut sink = TestSink::new();

    // Direct ansi_output of a known byte sequence.
    sink.ansi_output(ansi::CURSOR_HOME).unwrap();
    sink.ansi_output(b"hello").unwrap();
    sink.flush().unwrap();

    // Verify byte capture: CURSOR_HOME (3 bytes) + "hello" (5 bytes) = 8 bytes.
    assert_eq!(sink.out.len(), 8);
    assert_eq!(&sink.out[0..3], ansi::CURSOR_HOME);
    assert_eq!(&sink.out[3..], b"hello");
    assert_eq!(sink.flush_count, 1);

    // Use the trait default `move_cursor` path — should emit
    // `ESC[2;3H` (move to row=2 col=3) on first call, and elide
    // a redundant move on second call to the same coordinates.
    let mut sink2 = TestSink::new();
    sink2.move_cursor(2, 3).unwrap();
    let len_after_first = sink2.out.len();
    assert!(len_after_first > 0, "first move_cursor must emit bytes");
    // ANSI cursor move is `ESC[<row>;<col>H` — verify the suffix.
    assert!(sink2.out.starts_with(b"\x1b["));
    assert!(sink2.out.ends_with(b"H"));
    // Both row=2 and col=3 must appear as ASCII digits.
    let s = std::str::from_utf8(&sink2.out).unwrap();
    assert!(s.contains('2'));
    assert!(s.contains('3'));

    // Second call with identical coordinates is elided (no bytes).
    sink2.move_cursor(2, 3).unwrap();
    assert_eq!(
        sink2.out.len(),
        len_after_first,
        "redundant move_cursor must be elided"
    );
}


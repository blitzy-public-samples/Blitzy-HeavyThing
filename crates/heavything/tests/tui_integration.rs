//! Integration tests for the `heavything::tui` subsystem.
//!
//! These tests exercise the public API surface of the TUI subsystem from
//! an external-consumer perspective (the `tests/` directory produces a
//! separate compilation unit that links against the `heavything` library
//! as if it were any downstream crate). Per AAP §0.3.1.2 they verify
//! "rendered-frame byte comparison against expected ANSI" so the byte
//! stream generated by widget composition is checked against the
//! exact escape sequences specified in the FASM `tui_render.inc` /
//! `tui_ansi.inc` reference.
//!
//! The 18 tests are organized into 8 sections matching the QA
//! checkpoint Phase 2 scope:
//!
//! | Section | Purpose | Test Count |
//! |---------|---------|-----------|
//! | 1. ANSI Constants | Byte-literal verification of ALT_SCREEN_ENTER, ALT_SCREEN_EXIT, CURSOR_HOME, CLEAR_SCREEN, ACS_ENTER/EXIT, SGR_RESET | 5 |
//! | 2. Geometry | Point + Rect API with half-open semantics, intersect, contains, align_offset | 5 |
//! | 3. Widget Tree | TuiBackground draw composition + TuiVLine/TuiHLine factory verification | 2 |
//! | 4. ACS Lines | VLINE_CHAR=0x2502 / HLINE_CHAR=0x2500 stored verbatim in line widgets | 1 |
//! | 5. Alt-Screen Mode | TERMINAL_ALTERNATESCREEN=true config; ALT_SCREEN_ENTER/EXIT byte equality | 2 |
//! | 6. Raw Terminal | WindowSize struct semantics; RawTerminal::exit_pending() default state | 1 |
//! | 7. Background Widget | TuiBackground field accessors + initialization invariants | 1 |
//! | 8. TuiError | Variant construction + Display formatting for all three io::Error variants | 1 |
//!
//! ## Test infrastructure: `TestSink`
//!
//! The `TestSink` struct used by `tui::render` unit tests is private to
//! that module's `#[cfg(test)] mod tests` block, which means it cannot
//! be re-imported from this integration test crate. We therefore provide
//! a minimal local re-implementation that captures every byte written
//! via `Renderer::ansi_output` into a `Vec<u8>`. This lets us verify the
//! exact ANSI byte sequences the renderer emits, which is the spirit of
//! AAP §0.3.1.2's "rendered-frame byte comparison".
//!
//! ## Critical constraint: no `RawTerminal::enter()` calls
//!
//! `RawTerminal` is a process-wide singleton enforced by an `OnceLock`
//! [`INIT_GUARD`](heavything::tui::terminal); calling `enter()` here
//! would conflict with the `test_raw_terminal_roundtrip` test in
//! `ffi_boundary.rs` and break parallel test execution. This file
//! therefore only verifies non-syscalling invariants of `WindowSize`,
//! `RawTerminal::exit_pending()` (an associated function, not a
//! method), and the Drop-aware byte sequences that `RawTerminal::enter`
//! and `Drop` emit (verified at the constant level via the `ansi`
//! module).

